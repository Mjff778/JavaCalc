package handcalc.entity;

/**
 * A sampled position of the pen, in canvas coordinates (y grows downwards).
 */
public final class Point {

    private final double x;
    private final double y;

    public Point(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
